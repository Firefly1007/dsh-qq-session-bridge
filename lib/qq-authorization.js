import { isDeepStrictEqual } from 'node:util';

function validId(value) {
  return typeof value === 'string' && value.length > 0 && value.trim() === value;
}

function routeOf(value) {
  return value && validId(value.provider) && validId(value.model)
    ? { provider: value.provider, model: value.model } : null;
}

function sameRoute(left, right) {
  return left && right && left.provider === right.provider && left.model === right.model;
}

function modelNotice(previous, selected, id) {
  const from = previous.provider === selected.provider ? previous.model : `${previous.provider}/${previous.model}`;
  const to = previous.provider === selected.provider ? selected.model : `${selected.provider}/${selected.model}`;
  const summary = `${from} → ${to}`;
  return { id, role: 'user', content: [{ type: 'text',
    text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]` }],
  source: { kind: 'model-selection', form: 'notice', summary: summary.length <= 120 ? summary : summary.slice(0, 119) + '…' } };
}

// The bridge must call admit only after authenticating and admitting the QQ event.
export function createQQAuthorization({ agent, controlTools, administratorIds = [], onTurnEnd, removeGuardOnDispose = false }) {
  if (!Array.isArray(controlTools) || !controlTools.length || !controlTools.every(validId)) {
    throw new TypeError('controlTools must explicitly name the delegation control tools');
  }
  if (!Array.isArray(administratorIds) || !administratorIds.every(validId)) {
    throw new TypeError('administratorIds must contain non-empty identity strings');
  }
  const controls = new Set(controlTools);
  const administrators = new Set(administratorIds);
  const accepted = new Map();
  let authorization;
  let activeStep;
  let pendingClaims = new Set();
  let remainingClaims = new Set();
  let stepClaims = new Set();
  let committedInput = false;
  let disposed = false;
  let lastRoute = null;
  let selectedRoute = null;
  let noticeExpected;
  let notice;
  const seenNotices = new Set();

  function observeRoute(event) {
    if (event.type === 'model/selection') selectedRoute = routeOf(event.data);
    if (event.type === 'request/header') {
      lastRoute = routeOf(event.data?.header?.config);
      if (sameRoute(lastRoute, selectedRoute)) selectedRoute = null;
    }
  }
  for (const event of agent.session.snapshotEvents?.() || []) {
    observeRoute(event);
    if (event.type === 'user/message' && event.data.source.kind === 'model-selection') seenNotices.add(event.data.id);
  }

  function active() {
    return !disposed && agent.status === 'running' && !!authorization && remainingClaims.size === 0
      && (!notice || notice.confirmed)
      && activeStep?.turn === authorization.turn && activeStep.step === authorization.step;
  }

  function consume(entry) {
    if (!entry) return false;
    entry.consumed = true;
    delete entry.message;
    return true;
  }

  const stopGuard = agent.ctx.tools.guard(execution => {
    if (!controls.has(execution.name)) return;
    if (execution.agent !== agent || !active() || !authorization.privileged) {
      return 'QQ administrator authorization required';
    }
  });

  const stopEvents = agent.ctx.on('session/event', (session, event) => {
    if (session !== agent.session) return;
    if (event.type === 'step/start') {
      activeStep = event.data;
      stepClaims = pendingClaims;
      remainingClaims = new Set(stepClaims);
      pendingClaims = new Set();
      committedInput = false;
      notice = null;
      noticeExpected = lastRoute && selectedRoute && !sameRoute(lastRoute, selectedRoute)
        ? { previous: lastRoute, selected: selectedRoute } : null;
      const previous = remainingClaims.size === 0 && authorization?.turn === activeStep.turn ? authorization : null;
      authorization = {
        ...activeStep,
        privileged: !!previous?.privileged,
        sendable: !!previous?.sendable,
        origin: previous?.origin ?? null,
        sendPermit: Object.freeze({}),
        sourceIds: new Set(previous ? previous.sourceIds : stepClaims),
        files: new Map(previous?.files || []),
      };
    }
    if (event.type === 'user/message' && activeStep) {
      const message = event.data;
      // rc.2 regenerates runtime-context itself; it neither authorizes nor satisfies a claimed QQ input.
      if (message.source.kind === 'runtime-context') return;
      if (message.source.kind === 'model-selection') {
        const replayed = seenNotices.has(message.id);
        seenNotices.add(message.id);
        // This fixed rc.2 notice is trusted only against durable selection and actual request-route facts.
        if (!stepClaims.has(message.id) && !accepted.has(message.id) && !replayed && !notice && noticeExpected
          && validId(message.id) && isDeepStrictEqual(message,
            modelNotice(noticeExpected.previous, noticeExpected.selected, message.id))) {
          notice = { selected: noticeExpected.selected, confirmed: false };
          return;
        }
      }
      const entry = accepted.get(message.id);
      const trusted = remainingClaims.has(message.id) && entry && !entry.consumed
        && isDeepStrictEqual(entry.message, message);
      const privileged = trusted && entry.origin === 'qq' && entry.allowDelegation && administrators.has(entry.senderId);
      const origin = trusted ? entry.origin : null;
      remainingClaims.delete(message.id);
      consume(entry);
      authorization.privileged = committedInput ? authorization.privileged && !!privileged : !!privileged;
      authorization.sendable = committedInput ? authorization.sendable && !!trusted && authorization.origin === origin : !!trusted;
      authorization.origin = committedInput && authorization.origin !== origin ? null : origin;
      if (trusted && entry.origin === 'qq' && Array.isArray(message.content)) {
        for (const part of message.content) {
          const ref = part?.type === 'file' ? part.attachment : null;
          if (ref && typeof ref.attachmentId === 'string' && ref.attachmentId && typeof ref.name === 'string'
            && Number.isSafeInteger(ref.bytes) && ref.bytes >= 0) authorization.files.set(ref.attachmentId, structuredClone(ref));
        }
      }
      committedInput = true;
    }
    if (event.type === 'step/end') {
      if (authorization && (remainingClaims.size || (notice && !notice.confirmed))) {
        authorization.privileged = false;
        authorization.sendable = false;
      }
      activeStep = undefined;
    }
    if (event.type === 'turn/end' && authorization && !remainingClaims.size && (!notice || notice.confirmed)) {
      try { onTurnEnd?.({ turn: event.data.turn, reason: event.data.reason, origin: authorization.origin,
        sendable: authorization.sendable }); } catch { /* Observers cannot affect authorization. */ }
    }
    if (event.type === 'turn/start' || event.type === 'turn/end') {
      authorization = undefined;
      activeStep = undefined;
      pendingClaims.clear();
      remainingClaims.clear();
      stepClaims.clear();
      notice = null;
      noticeExpected = null;
    }
    if (event.type === 'request/header' && notice) notice.confirmed = !!sameRoute(routeOf(event.data?.header?.config), notice.selected);
    observeRoute(event);
  });
  const stopClaims = agent.ctx.on('agent/inbox/claimed', ({ agent: subject, message }) => {
    if (subject === agent) pendingClaims.add(message.id);
  });
  const stopDiscards = agent.ctx.on('agent/inbox/discarded', ({ agent: subject, message }) => {
    if (subject !== agent) return;
    consume(accepted.get(message.id));
  });

  function admitMessage(message, identity) {
    if (disposed) throw new Error('QQ authorization is disposed');
    if (!validId(message?.id) || message.role !== 'user' || !message.source
      || !validId(message.source.kind) || message.source.kind === 'runtime-context') {
      throw new TypeError('A user message with a valid source is required');
    }
    if (accepted.has(message.id)) throw new Error('QQ message identity was already admitted');
    accepted.set(message.id, { ...identity, message: structuredClone(message) });
  }

  return {
    admit(message, senderId, options = {}) {
      if (!validId(senderId)) throw new TypeError('A valid QQ sender identity is required');
      if (!options || typeof options !== 'object' || Array.isArray(options)
        || Object.keys(options).some(key => key !== 'allowDelegation')
        || (options.allowDelegation !== undefined && typeof options.allowDelegation !== 'boolean')) {
        throw new TypeError('allowDelegation must be a boolean');
      }
      admitMessage(message, { origin: 'qq', senderId, allowDelegation: options.allowDelegation ?? true });
    },
    admitProactive(message) { admitMessage(message, { origin: 'proactive' }); },
    admitReminder(message) { admitMessage(message, { origin: 'reminder' }); },
    invalidate(messageId) {
      if (!validId(messageId)) return false;
      const found = consume(accepted.get(messageId));
      if (authorization?.sourceIds.has(messageId)) {
        authorization.privileged = false;
        authorization.sendable = false;
        authorization.sendPermit = Object.freeze({});
      }
      return found;
    },
    canDelegate() { return active() && authorization.privileged; },
    setAdministratorIds(ids) {
      if (!Array.isArray(ids) || !ids.every(validId)) throw new TypeError('administratorIds must contain non-empty identity strings');
      administrators.clear();
      for (const id of ids) administrators.add(id);
      if (authorization) authorization.privileged = false;
    },
    captureSendPermit() { return active() && authorization.sendable ? authorization.sendPermit : null; },
    canSend(permit) {
      return active() && authorization.sendable && (permit === undefined || permit === authorization.sendPermit);
    },
    resolveQQFile(id, permit) {
      if (!active() || !authorization.sendable || authorization.origin !== 'qq' || permit !== authorization.sendPermit) return null;
      const ref = authorization.files.get(id);
      return ref ? structuredClone(ref) : null;
    },
    dispose() {
      if (disposed) return;
      disposed = true;
      authorization = undefined;
      activeStep = undefined;
      accepted.clear();
      pendingClaims.clear();
      remainingClaims.clear();
      stepClaims.clear();
      seenNotices.clear();
      lastRoute = null;
      selectedRoute = null;
      notice = null;
      noticeExpected = null;
      stopEvents();
      stopClaims();
      stopDiscards();
      // The host-level guard must already be revoked before scoped protection is removed.
      if (removeGuardOnDispose && typeof stopGuard === 'function') stopGuard();
    },
  };
}
